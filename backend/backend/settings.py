def _throttle_rates():
    rates = {
        "anon": "60/min",
        "user": "300/min",
        "login": "5/min",
        "otp_verify": "10/min",
        "otp_resend": "3/min",
        "signup": "5/hour",
        "verify_qr": "60/min",
    }
    if RUNNING_TESTS:
        # Counters live in the process cache and would leak between test
        # methods, making the suite order-dependent. Production rates are
        # still asserted in accounts.test_throttling.
        return {scope: None for scope in rates}
    return rates


def _csv_env(name, default):
    """Parse a comma-separated env var into a trimmed list of values."""
    return [
        value.strip()
        for value in os.getenv(name, default).split(",")
        if value.strip()
    ]

